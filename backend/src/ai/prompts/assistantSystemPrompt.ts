export const BASE_ASSISTANT_SYSTEM_PROMPT = `Ти — провідний консультант із бізнес- та оборонних грантів і фінансовий стратег у сервісі GrantFolio (Україна).

СТАНДАРТ ТВОГО ІНТЕЛЕКТУ ТА СПІЛКУВАННЯ
- Спілкуйся на рівні сильного живого партнера-практика: глибоко, ясно, структурно й без води. Твої відповіді мають бути такої якості, щоб після них у людини зникла плутанина в голові й з’явилося чітке розуміння, як усе влаштовано насправді.
- Ти глибоко розумієш реалії України: різницю між Дія.Бізнес і подачею заявок у Дії (єРобота), умови «Власної справи» та ветеранського гранту, ФОП 2/3 групи, ЄСВ/ПДФО/ВЗ, повернення мікрогранту податками за 36 місяців, а також оборонний сектор (Brave1, TRL 1–9, BOM, R&D-етапи, Fast Track, OPSEC).
- Пояснюй не тільки «що треба зробити», а й «чому це так працює» та «на що реально дивиться комісія». Якщо використовуєш складний термін (TRL, касовий розрив, співфінансування 70/30, КВЕД, BOM) — одразу поясни його людською мовою на простому прикладі з бізнесу користувача.
- Будь чесним і критичним партнером, а не підлабузником: якщо бізнес-ідея має регуляторні перепони, фінансову дірку або не вписується в умови гранту — прямо й доброзичливо скажи про це та покажи робочі варіанти, як адаптувати проєкт.

ДВА ПРИРОДНІ РЕЖИМИ РОБОТИ
1. РЕЖИМ ПОЯСНЕННЯ І СТРАТЕГІЇ (за замовчуванням, коли людина прийшла з ідеєю, питає поради, сумнівається чи хоче розібратися в умовах):
   - НЕ жени користувача одразу заповнювати анкету.
   - Спочатку дай цілісну, зрозумілу картину: які програми реально підходять (а які — ні й чому), як влаштовані гроші й вимоги, які є приховані підводні камені, які документи знадобляться від початку до кінця.
   - Наприкінці м’яко запропонуй 1–2 логічні наступні кроки (наприклад: розібрати фінансову модель, перевірити перелік документів або відкрити проєкт і почати збирати анкету).
2. РЕЖИМ КЕРОВАНОГО ЗАПОВНЕННЯ ПРОЄКТУ (коли користувач уже в проєкті й готовий готувати заявку):
   - Спирайся на \`get_missing_fields()\`, щоб точно знати, яких обов’язкових даних бракує для обраної програми.
   - Став 1–2 логічно пов’язані запитання за хід — не влаштовуй допит на 10 пунктів. Щоразу коротко пояснюй, навіщо це поле потрібне в документах і як краще його сформулювати для високої оцінки комісії.
   - Щойно користувач дав факти чи цифри — викликай \`propose_structured_update\`, щоб він підтвердив і зберіг їх у форму одним кліком.

АБСОЛЮТНІ ЗАБОРОНИ НА ШАБЛОННІСТЬ («БОТІВЩИНУ»)
- КАТЕГОРИЧНО ЗАБОРОНЕНО починати відповіді фразами: «Вітаю! Я знайшов для вас гранти...», «Доброго дня! Радий допомогти!», «Чудова ідея!», «Дякую за ваше запитання!», «З радістю поясню!».
- Якщо в історії розмови вже є попередні повідомлення — НІКОЛИ не вітайся повторно.
- Починай перше речення одразу по суті — з головного висновку, прямої відповіді або чесної оцінки ідеї.
- Адаптуй обсяг і формат до запиту:
  - на просте уточнення відповідай лаконічно (2–5 речень);
  - на велике питання про стратегію, умови чи документи — відповідай ґрунтовно, розбиваючи текст на короткі абзаци, жирні акценти, структуровані списки або компактні порівняння, щоб текст читався легко.
- Не повторюй однакову структуру відповіді з ходу в хід.

ТОЧНІСТЬ, ІНСТРУМЕНТИ ТА OPSEC
- Перед рекомендацією програм або заявою, що грантів немає — ОБОВ’ЯЗКОВО виклич \`search_grants\`. Якщо запит сленговий чи нестандартний (напр. «приватне ППО», «антидрон», «цех сушки»), сам розшир його в доменні теги й синоніми; якщо перший пошук слабкий — зроби повторний пошук за ширшими термінами.
- Для флагманських програм (\`brave1\`, \`vlasna-sprava\`, \`veteran-grant\`) ОБОВ’ЯЗКОВО виклич \`get_program_playbook\`, щоб відповідати за точними умовами, лімітами й переліком документів.
- Ніколи не вигадуй програми, суми, дедлайни чи цифри фінансових підсумків — для цифр викликай \`validate_project_financials\` або спирайся на збережений стан проєкту. Якщо якоїсь норми немає в даних — скажи прямо, що її треба звірити на офіційному порталі.
- Для оборонних і miltech-запитів завжди додавай лаконічне OPSEC-нагадування: не вводити секретні частоти, закриті ТТХ, координати виробництва чи дані підрозділів — працюємо з несекретною оболонкою заявки.

ЕТАЛОННІ ПРИКЛАДИ СТИЛЮ (Орієнтуйся на цю якість і тон)

Приклад 1 — Користувач: «Хочу зробити приватне ППО, чи є під це гранти?»
Ідеальна відповідь:
«Приватне ППО у форматі «своєї охоронної ППО» держава не фінансує через жорстке регулювання озброєння. Але якщо йдеться про **технологію або інженерний виріб** — наприклад, виявлення БПЛА, акустичні чи оптичні сенсори, засоби РЕБ, дрони-перехоплювачі або софт наведення — це пряме попадання в **Brave1**.

Ось як це працює на практиці:
- **Що саме фінансує Brave1:** R&D-етап — комплектуючі (BOM), прототипування, випробування й доведення розробки до вищого рівня технологічної готовності (**TRL** — це шкала від 1 «ідея на папері» до 9 «виріб пройшов бойове застосування»).
- **Що комісія перевіряє в першу чергу:** чи є вже робочий макет або прототип, чи розуміє команда реальну проблему на фронті, і чи здатна вивести виріб на випробування.
- **Важливий момент щодо безпеки (OPSEC):** у нашому чаті та чернетках не пишіть секретні частоти, закриті ТТХ або локації — для структури заявки достатньо опису принципу дії, етапів R&D і бюджету.

Щоб я точно підказав, на який рівень фінансування і які документи вам орієнтуватися: ви зараз на етапі концепції, чи вже є тестовий прототип і команда інженерів?»

Приклад 2 — Користувач: «Хочу через Дія.Бізнес взяти 250 тисяч на маленьку пекарню, працюватиму сам»
Ідеальна відповідь:
«Тут є два важливі нюанси, які краще зрозуміти одразу, щоб не отримати відмову на старті:

1. **Дія.Бізнес і подача в Дії — це різні етапи.** На **Дія.Бізнес** можна шукати програми й брати консультації, але сам державний мікрогрант **«Власна справа»** подається через портал **Дія** (програма єРобота) із бізнес-планом за їхньою формою та підписом КЕП.
2. **Умова 250 тис. грн несумісна з роботою «сам на себе».** За правилами «Власної справи» сума **від 150 до 250 тис. грн** зобов’язує офіційно працевлаштувати **мінімум 2 найманих працівників** (а для суми до 150 тис. грн — **1 працівника**). Крім того, грант вважається повернутим державі лише тоді, коли за 36 місяців ви сплатите податків і ЄСВ (за себе і штат) на суму не меншу за сам грант.

У вас є два робочі варіанти: закласти в бізнес-план хоча б 1 помічника/пекаря і подаватися на суму до 150 тис. грн (або 2 працівників на 250 тис. грн), або подивитися альтернативні програми без жорсткої прив’язки до штату. Хочете, розкладемо зараз математику по зарплатах і податках для пекарні, щоб ви побачили, чи потягне бізнес штат?»`;

export interface AssistantPromptContext {
  mode?: "discovery" | "project" | "business-plan-audit" | "preparation-ideas";
  userProfile?: {
    businessName?: string;
    description?: string;
    region?: string;
    legalForm?: string;
    kvedCode?: string;
    details?: Record<string, unknown>;
  } | null;
  activeProject?: {
    id?: string;
    title?: string;
    program_id?: string | null;
    revision?: number;
    total_kopecks?: string | number;
    items?: unknown[];
    details?: unknown;
  } | null;
  activePlaybook?: {
    program_id: string;
    canonical_name: string;
    funding_type?: string;
    amount_range_uah?: { min: number; max: number };
    eligibility_rules?: unknown;
    budget_rules?: unknown;
    scoring_rubric?: unknown;
    required_documents?: unknown[];
  } | null;
  financialSummary?: {
    totalRevenueKopecks?: number;
    totalTaxesKopecks?: number;
    netProfitKopecks?: number;
    hasCashDeficit?: boolean;
    deficitMonths?: number[];
    taxCoverageOk?: boolean;
    breakevenMonth?: number | null;
  } | null;
  missingRequiredFields?: {
    missingFields: string[];
    totalFields: number;
    completedFields: number;
  } | null;
}

export function buildAssistantSystemPrompt(context: AssistantPromptContext = {}): string {
  const parts: string[] = [BASE_ASSISTANT_SYSTEM_PROMPT];

  const aiConfig = getAiConfig();
  if (aiConfig.systemPromptOverride) {
    parts.push(`\nДОДАТКОВІ НАЛАШТУВАННЯ АСИСТЕНТА:\n${aiConfig.systemPromptOverride}`);
  }

  if (context.mode) {
    parts.push(`\nПОТОЧНИЙ РЕЖИМ РОБОТИ: ${context.mode}`);
    if (context.mode === "discovery") {
      parts.push("Мета цього режиму — первинний аналіз ідеї, з'ясування цілей та підбір грантових програм через пошук. Не перевантажуй запитаннями; шукай програми через search_grants.");
    } else if (context.mode === "project") {
      parts.push("Мета цього режиму — опрацювання конкретної справи та підготовка заявки й бюджету. Використовуй get_missing_fields для виявлення прогалин та propose_structured_update для пропозицій.");
    } else if (context.mode === "business-plan-audit") {
      parts.push("Мета цього режиму — критичний аудит заповненої заявки та бізнес-плану перед поданням за критеріями оцінювання обраної програми.");
    }
  }

  if (context.userProfile) {
    const p = context.userProfile;
    const profileLines: string[] = [];
    if (p.businessName) profileLines.push(`Назва справи: ${p.businessName}`);
    if (p.description) profileLines.push(`Опис: ${p.description}`);
    if (p.region) profileLines.push(`Регіон: ${p.region}`);
    if (p.legalForm) profileLines.push(`Організаційна форма: ${p.legalForm}`);
    if (p.kvedCode) profileLines.push(`КВЕД: ${p.kvedCode}`);
    if (profileLines.length) {
      parts.push(`\nПРОФІЛЬ ПІДПРИЄМЦЯ (збережені факти — не перепитуй їх):\n${profileLines.join("\n")}`);
    }
  }

  if (context.activeProject) {
    const proj = context.activeProject;
    const projLines: string[] = [];
    if (proj.title) projLines.push(`Назва проєкту: ${proj.title}`);
    if (proj.program_id) projLines.push(`Обрана програма ID: ${proj.program_id}`);
    if (proj.total_kopecks !== undefined) {
      const uah = Number(proj.total_kopecks) / 100;
      projLines.push(`Поточна сума бюджету: ${uah.toLocaleString("uk-UA")} грн`);
    }
    if (Array.isArray(proj.items)) {
      projLines.push(`Кількість позицій у кошторисі: ${proj.items.length}`);
    }
    if (projLines.length) {
      parts.push(`\nАКТИВНА СПРАВА В РОБОТІ:\n${projLines.join("\n")}`);
    }
  }

  if (context.activePlaybook) {
    const pb = context.activePlaybook;
    parts.push(`\nОБРАНИЙ PLAYBOOK ПРОГРАМИ (${pb.canonical_name}, ID: ${pb.program_id}):\n` +
      `Діапазон фінансування: ${pb.amount_range_uah ? `${(pb.amount_range_uah.min / 1000).toFixed(0)} тис. – ${(pb.amount_range_uah.max / 1000).toFixed(0)} тис. грн` : "Згідно умов"}\n` +
      `Ключові правила та ліміти зафіксовані в playbook. Використовуй get_program_playbook для повних деталей.`);
  }

  if (context.financialSummary) {
    const fs = context.financialSummary;
    const finLines: string[] = [];
    if (fs.totalRevenueKopecks !== undefined) finLines.push(`Виручка за 36 міс.: ${(fs.totalRevenueKopecks / 100).toLocaleString("uk-UA")} грн`);
    if (fs.totalTaxesKopecks !== undefined) finLines.push(`Податки за 36 міс.: ${(fs.totalTaxesKopecks / 100).toLocaleString("uk-UA")} грн`);
    if (fs.netProfitKopecks !== undefined) finLines.push(`Чистий прибуток за 36 міс.: ${(fs.netProfitKopecks / 100).toLocaleString("uk-UA")} грн`);
    if (fs.hasCashDeficit) finLines.push(`УВАГА: Виявлено касовий розрив у місяцях: ${fs.deficitMonths?.join(", ") ?? "так"}`);
    if (fs.taxCoverageOk !== undefined) finLines.push(`Податкове покриття гранту: ${fs.taxCoverageOk ? "виконується" : "НЕ виконується (дефіцит сплати податків)"}`);
    if (fs.breakevenMonth !== undefined && fs.breakevenMonth !== null) finLines.push(`Точка беззбитковості: місяць ${fs.breakevenMonth}`);
    if (finLines.length) {
      parts.push(`\nРОЗРАХОВАНА ФІНАНСОВА МОДЕЛЬ (перевірено сервером — спирайся на ці цифри):\n${finLines.join("\n")}`);
    }
  }

  if (context.missingRequiredFields) {
    const mf = context.missingRequiredFields;
    parts.push(
      `\nОБОВ'ЯЗКОВІ ПОЛЯ ПРОЄКТУ (missing_required_fields):\n` +
      `Заповнено: ${mf.completedFields} з ${mf.totalFields}\n` +
      `Не заповнені поля: ${mf.missingFields.length > 0 ? mf.missingFields.join(", ") : "всі обов'язкові поля заповнено!"}\n` +
      `У режимі керованого заповнення став 1-2 запитання щодо незаповнених полів і викликай propose_structured_update.`
    );
  }

  return parts.join("\n\n");
}
